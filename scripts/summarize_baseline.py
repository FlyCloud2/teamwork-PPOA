#!/usr/bin/env python
"""Generate W2 evidence summaries from the verified three-run manifest."""
import csv
import json
from pathlib import Path
import statistics

from run import REPO, atomic_json
from verify_runs import verify_baseline


def main():
    configs = sorted(verify_baseline(), key=lambda config: config["env"])
    summary = []
    for config in configs:
        path = REPO / "runs" / config["run_id"] / "progress.csv"
        with path.open(encoding="utf-8", newline="") as handle:
            rows = list(csv.DictReader(handle))
        returns = [float(row["episode_return"]) for row in rows[-10:]]
        summary.append({
            "env": config["env"], "run_id": config["run_id"], "actual_steps": config["actual_steps"],
            "updates": config["updates"], "wall_time_s": config["wall_time_s"],
            "last_recorded_episode_return": float(rows[-1]["episode_return"]),
            "last_10_update_return_mean": statistics.mean(returns),
            "return_code": config["return_code"],
        })
    atomic_json(REPO / "logs" / "w2_summary.json", {"runs": summary, "aggregation": "latest completed training episode at each update; last 10 updates, not episodes or seeds"})
    lines = ["# W2 baseline evidence", "", "Generated by `scripts/summarize_baseline.py` from verified CSV files; do not hand-edit numbers.", "",
             "All three runs use seed 0, clip0.2, CPU, one thread, Gymnasium 0.29.1 and MuJoCo 3.1.6.",
             "Each run has exactly 1,000,000 environment steps and 489 updates. Full configuration and logs are linked below.", "",
             "| Environment | Steps | Updates | Wall time (min) | Last logged return | Last 10 updates mean |", "|---|---:|---:|---:|---:|---:|"]
    for row in summary:
        lines.append(f"| {row['env']} | {row['actual_steps']:,} | {row['updates']} | {row['wall_time_s']/60:.2f} | {row['last_recorded_episode_return']:.2f} | {row['last_10_update_return_mean']:.2f} |")
    lines += ["", "Returns are raw **training** episode returns sampled at update boundaries. The last-ten-update mean is descriptive and may repeat an episode; it is neither an evaluation score nor a multi-seed estimate. W2 does not establish the C1 ranking.", "", "![W2 baseline training curves](../figures/w2_baseline.png)", "", "## Raw evidence", ""]
    for row in summary:
        base = "../runs/" + row["run_id"]
        lines.append(f"- {row['env']}: [config]({base}/config.json), [progress]({base}/progress.csv), [stdout]({base}/stdout.log).")
    lines += ["", "- [Run index](../logs/runs.csv), [accepted matrix](../logs/w2_baseline.json), [machine-readable summary](../logs/w2_summary.json).",
              "- [Environment snapshot](../env.txt), [dependency lock](../requirements-lock.txt), [setup](setup.md), [deviations](deviations.md).",
              "", "## Recheck", "", "```powershell", "python -m unittest discover -s tests -v", "python scripts/verify_runs.py --baseline",
              "python scripts/plot.py --baseline --out figures/w2_baseline.png", "python scripts/summarize_baseline.py", "```", "",
              "The original failed Unicode-path smoke remains in the index with status `failed`; the successful 20,000-step smoke is separate. Neither is part of the accepted matrix.",
              "The runs started from a modified worktree based on `bcb3bc9`. Each run records the SHA-256 of the training sources it executed, and the three hashes agree; `src/ppo_args.py` and `src/ppo_continuous_action.py` were edited in W3 (KL-penalty flags), so the current files no longer match the executed W2 sources. `scripts/verify_runs.py --baseline` reports that drift instead of failing, and `git_dirty` is recorded honestly.", ""]
    path = REPO / "docs" / "w2_baseline.md"
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
