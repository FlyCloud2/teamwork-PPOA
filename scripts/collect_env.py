#!/usr/bin/env python
"""给机器拍快照，让陌生人能判断我们的数字是否可比。

为什么要有它
    "在我机器上能跑"不是复现。本脚本写出 env.txt：
    操作系统版本、CPU、内存、GPU 与驱动、Python 解释器、
    产出这些数字的 git commit，以及完整的 pip freeze。
    环境或 commit 一变就重跑一次，env.txt 提交进仓库。

它写出什么
    仓库根目录下的 env.txt（每次运行覆盖）。

怎么运行
    python scripts/collect_env.py
    python scripts/collect_env.py --out env.txt

示例
    D:\\miniconda3\\envs\\ppo-repro\\python.exe scripts\\collect_env.py
    写出的 env.txt 里有一行 "commit:"，标明这份证据属于哪个 HEAD。
"""
import argparse
import importlib.metadata as md
import os
import platform
import shutil
import subprocess
import sys
from datetime import datetime
# 来源标注：AI 辅助起草 —— 见 AI_USAGE.md。由 <name> 于 <date> 复核。
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

# 这些库的版本会真正改变结果。显式列出，
# 读者就不必去 diff 一份两百行的 freeze 才能发现 gymnasium 那个版本钉。
KEY_PACKAGES = ["torch", "gymnasium", "mujoco", "numpy", "pandas", "matplotlib",
                "tensorboard", "imageio", "tqdm"]


def git(*args, default="unknown"):
    exe = shutil.which("git") or r"C:\Program Files\Git\cmd\git.exe"
    try:
        return subprocess.check_output([exe, *args], cwd=REPO, text=True,
                                       stderr=subprocess.DEVNULL).strip()
    except Exception:
        return default


def total_memory_gib() -> str:
    """Windows has no os.sysconf; ask the kernel through ctypes instead of a shell call."""
    try:
        import ctypes

        class MEMORYSTATUSEX(ctypes.Structure):
            _fields_ = [("dwLength", ctypes.c_ulong), ("dwMemoryLoad", ctypes.c_ulong),
                        ("ullTotalPhys", ctypes.c_ulonglong), ("ullAvailPhys", ctypes.c_ulonglong),
                        ("ullTotalPageFile", ctypes.c_ulonglong), ("ullAvailPageFile", ctypes.c_ulonglong),
                        ("ullTotalVirtual", ctypes.c_ulonglong), ("ullAvailVirtual", ctypes.c_ulonglong),
                        ("ullAvailExtendedVirtual", ctypes.c_ulonglong)]

        m = MEMORYSTATUSEX()
        m.dwLength = ctypes.sizeof(MEMORYSTATUSEX)
        ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(m))
        return f"{m.ullTotalPhys / 1024 ** 3:.1f} GiB"
    except Exception:
        return "unknown"


def gpu_lines() -> list:
    try:
        import torch

        if not torch.cuda.is_available():
            return ["gpu: none (cuda unavailable)"]
        name = torch.cuda.get_device_name(0)
        cap = ".".join(str(x) for x in torch.cuda.get_device_capability(0))
        return [f"gpu: {name} (compute capability {cap})",
                f"cuda runtime: {torch.version.cuda}",
                f"cudnn: {torch.backends.cudnn.version()}"]
    except Exception as e:  # torch 缺失或损坏 —— 但仍然值得记录下来
        return [f"gpu: unknown ({e})"]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=REPO / "env.txt")
    a = ap.parse_args()

    # 快照描述工作区时把「它自己」排除在外：它不可能既被写出、
    # 又不在工作区里；若把它算成未跟踪产物，
    # 每份快照都会报一条毫无意义的警告。
    status = [ln for ln in git("status", "--porcelain", default="").splitlines()
              if not ln.strip().endswith(a.out.name)]

    lines = [
        "# Environment snapshot -- generated by scripts/collect_env.py, do not hand-edit.",
        f"generated: {datetime.now().isoformat(timespec='seconds')}",
        f"commit: {git('rev-parse', 'HEAD')}",
        f"commit_short: {git('rev-parse', '--short', 'HEAD')}",
        f"branch: {git('rev-parse', '--abbrev-ref', 'HEAD')}",
        # 有意拆成两个字段：「代码与 commit 不一致」和「存在未跟踪的 run 产物」
        # 是两种不同的警告；合成一个 dirty 会把前者
        # 藏在后者背后。
        f"code_modified_since_commit: {bool(git('status', '--porcelain', '--untracked-files=no', default=''))}",
        f"untracked_artifacts_present: {bool(status)}",
        "",
        "## host",
        f"platform: {platform.platform()}",
        f"machine: {platform.machine()}",
        f"processor: {platform.processor()}",
        f"cpu_count: {os.cpu_count()}",
        f"memory: {total_memory_gib()}",
        *gpu_lines(),
        "",
        "## python",
        f"python: {sys.version.split()[0]}",
        f"executable: {sys.executable}",
        f"conda_env: {os.environ.get('CONDA_DEFAULT_ENV', '(none)')}",
        "",
        "## key packages",
    ]
    for name in KEY_PACKAGES:
        try:
            lines.append(f"{name}: {md.version(name)}")
        except md.PackageNotFoundError:
            lines.append(f"{name}: NOT INSTALLED")
    lines += ["", "## pip freeze"]
    for dist in sorted(md.distributions(), key=lambda d: d.metadata["Name"].lower()):
        lines.append(f"{dist.metadata['Name']}=={dist.version}")

    a.out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
